"""
Reverse proxy in front of the backend.

Every request, whatever its method and path, is forwarded to the backend and
the backend's answer is relayed unchanged. All the demo's endpoints live in the
backend, so each call is a two-service distributed trace.
"""

import logging
import os
import uuid
from logging.config import dictConfig

import requests
from flask import Flask, Response, g, has_app_context, request

wapp = Flask(__name__)

# Where requests are forwarded to. Overridable via env so the same image runs
# in-cluster and on a laptop (e.g. BACKEND_URL=http://127.0.0.1:5000/).
# The default is the namespace-relative Service name rather than a full
# .svc.cluster.local FQDN: it resolves through the pod's DNS search path, so
# it keeps working if this app is deployed into a different namespace.
BACKEND_URL = os.environ.get("BACKEND_URL", "http://dydemo-backend-service/")

# Seconds to wait on the backend before giving up. Must exceed the backend's
# slowest deliberate response (/latency's 5s tail), or that tail turns into
# 504s, and stay under loadgen's 10s MAX_TIME, so a hung backend shows up as a
# 504 rather than a loadgen-side timeout. Tune it down (or point BACKEND_URL at something slow) to demo timeout
# behaviour on purpose.
BACKEND_TIMEOUT = float(os.environ.get("BACKEND_TIMEOUT", "8"))

# Correlation ID shared by the gateway and the backend. Taken from the caller
# if it sent one, generated otherwise, then forwarded to the backend and
# returned to the caller, so one call can be followed across both services.
REQUEST_ID_HEADER = "X-Request-ID"

# Not forwarded in either direction. Hop-by-hop headers describe one connection
# only (RFC 9110 7.6.1). Host must be the backend's. Content-Length and
# Content-Encoding are dropped on the way back because requests has already
# decoded the body, so the originals would no longer match it. Trace context
# headers are left to OneAgent, which sets them on the outgoing call itself.
HOP_BY_HOP = {
    "connection", "keep-alive", "proxy-authenticate", "proxy-authorization",
    "te", "trailer", "transfer-encoding", "upgrade",
}
NOT_FORWARDED = HOP_BY_HOP | {"host", "traceparent", "tracestate", "x-dynatrace"}
NOT_RETURNED = HOP_BY_HOP | {"content-length", "content-encoding"}


# Stamps every log record with the current request's ID, '-' outside a
# request. Done at record creation rather than in a handler filter, so it covers
# every logger and handler, including ones added later.
_make_record = logging.getLogRecordFactory()


def _record_with_request_id(*args, **kwargs):
    record = _make_record(*args, **kwargs)
    record.request_id = g.get("request_id", "-") if has_app_context() else "-"
    return record


logging.setLogRecordFactory(_record_with_request_id)


dictConfig(
    {
        "version": 1,
        "formatters": {
            "default": {
                "format": "[%(asctime)s] %(levelname)s in %(module)s "
                "[request_id=%(request_id)s]: %(message)s",
            },
        },
        "handlers": {
            "wsgi": {
                "class": "logging.StreamHandler",
                "stream": "ext://flask.logging.wsgi_errors_stream",
                "formatter": "default",
            },
        },
        "root": {
            "level": "INFO",
            "handlers": ["wsgi"],
        },
    }
)


@wapp.before_request
def assign_request_id():
    g.request_id = request.headers.get(REQUEST_ID_HEADER) or uuid.uuid4().hex


@wapp.after_request
def return_request_id(response):
    response.headers[REQUEST_ID_HEADER] = g.request_id
    return response


def gateway_error(status, message):
    """A response generated by the gateway itself, not relayed."""
    return Response(f"{message}\n", status=status, mimetype="text/plain")


@wapp.route("/", defaults={"path": ""}, methods=["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"])
@wapp.route("/<path:path>", methods=["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"])
def proxy(path):
    url = BACKEND_URL.rstrip("/") + "/" + path
    headers = {k: v for k, v in request.headers if k.lower() not in NOT_FORWARDED}
    headers[REQUEST_ID_HEADER] = g.request_id
    wapp.logger.info("%s /%s -> %s", request.method, path, url)
    try:
        upstream = requests.request(
            request.method,
            url,
            params=request.args,
            data=request.get_data(),
            headers=headers,
            timeout=BACKEND_TIMEOUT,
            allow_redirects=False,
        )
    except requests.exceptions.Timeout:
        # Map to the status codes a gateway is supposed to use, so a backend
        # problem is distinguishable from the backend's own /server_error
        # rather than surfacing as an opaque Flask 500.
        wapp.logger.error("backend %s timed out after %ss", url, BACKEND_TIMEOUT)
        return gateway_error(504, "Backend timed out")
    except requests.exceptions.RequestException as exc:
        # Includes the dropped connection when /blowup kills a backend worker.
        wapp.logger.error("backend %s unreachable: %s", url, exc)
        return gateway_error(502, "Backend unreachable")
    returned = [(k, v) for k, v in upstream.headers.items() if k.lower() not in NOT_RETURNED]
    return Response(upstream.content, status=upstream.status_code, headers=returned)


if __name__ == "__main__":
    wapp.run(debug=True)
